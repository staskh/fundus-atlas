# ABOUTME: The write-up a benchmark run generates: what ran, on what, and what came out. Written
# ABOUTME: by the run rather than by hand, so it cannot drift from the numbers it describes.

from collections.abc import Iterable
from datetime import date
from pathlib import Path

from models.utils.grading import GRADES

#: Where the generated documents live, beside the catalogues they refer to.
DIRECTORY = Path(__file__).resolve().parents[2] / "docs" / "benchmarks"


def write_report(name: str, scored: list[dict[str, object]], into: Path = DIRECTORY) -> Path:
    """Write one benchmark's summary document and return where it went."""
    into.mkdir(parents=True, exist_ok=True)
    path = into / f"{name}.md"
    path.write_text("\n".join(_quality(scored)) + "\n")
    return path


def _quality(scored: list[dict[str, object]]) -> Iterable[str]:
    models = sorted({entry["model"] for entry in scored})
    units = sorted({entry["unit"] for entry in scored})
    yield "# Quality benchmark"
    yield ""
    yield (
        "Can a model tell whether a fundus photograph is good enough to measure? Each model here "
        "is asked that of every photograph in the datasets below, and its answer is compared with "
        "the grade the dataset itself published. This page is generated by the run: every number "
        "on it comes from `results/quality/`, and nothing was written by hand."
    )
    yield ""
    yield "## 1. What ran"
    yield ""
    yield "| Model | Pinned at | Grid it reads | Grid the network sees | Ensemble | Ran on |"
    yield "| --- | --- | --- | --- | --- | --- |"
    for model in models:
        declared = _first(scored, model)["declared"]
        upstream = declared.get("upstream", {})
        yield (
            f"| [{model}](../models/{model}.md) | {_pin(upstream)} | {declared['grid']}² | "
            f"{declared['network_grid']}² | {declared.get('ensemble', '—')} | "
            f"{declared.get('device', '—')} |"
        )
    yield ""
    yield "## 2. What it ran on"
    yield ""
    yield (
        "The unit is one dataset's subset and split, never a whole dataset: contamination is per "
        "split, and cameras are not interchangeable. Photographs whose field of view is under 512 "
        "pixels are excluded, and so is every photograph the repository has recorded a finding "
        "against."
    )
    yield ""
    yield "| Unit | Photographs | Ungraded by the dataset |"
    yield "| --- | --- | --- |"
    for unit in units:
        entry = _first(scored, unit=unit)
        summary = entry["summary"]
        yield (
            f"| {unit} | {summary['photographs']} | "
            f"{summary.get('without_reference', 0)} set aside |"
        )
    yield ""
    yield "## 3. Coverage: what each model was willing to answer"
    yield ""
    yield (
        "A model that declines a photograph has not got it wrong, and one that crashes on a "
        "photograph has not judged it. Both are counted here and neither is folded into the "
        "accuracy below."
    )
    yield ""
    yield "| Model | Unit | Graded | Declined | Failed | Coverage |"
    yield "| --- | --- | --- | --- | --- | --- |"
    for entry in scored:
        summary = entry["summary"]
        yield (
            f"| {entry['model']} | {entry['unit']} | {summary['graded']} | "
            f"{summary['declined']} | {summary['failed']} | {summary['coverage']:.3f} |"
        )
    yield ""
    yield "## 4. Worth measuring, or not"
    yield ""
    yield (
        "The one question every model here can be asked: is this photograph worth measuring? Good "
        "and usable count as yes, bad as no. Accuracy depends on where a model's threshold sits; "
        "the area under the ROC curve does not, and is the fairer comparison between models whose "
        "thresholds were set on different data."
    )
    yield ""
    yield "| Model | Unit | Photographs | Accuracy | ROC AUC | Cohen's κ | Marked |"
    yield "| --- | --- | --- | --- | --- | --- | --- |"
    for entry in scored:
        level = entry["summary"]["gradeable"]
        yield (
            f"| {entry['model']} | {entry['unit']} | {level['photographs']} | "
            f"{_number(level['accuracy'])} | {_number(level['roc_auc'])} | "
            f"{_number(level['kappa'])} | {entry['contamination']} |"
        )
    yield ""
    yield "## 5. The three grades"
    yield ""
    three = [entry for entry in scored if entry["summary"].get("three_class")]
    if not three:
        yield "No model in this run named all three grades."
    else:
        yield (
            "Only the models that grade in three classes appear here. The weighted κ is "
            "quadratic, which counts calling a good photograph bad as worse than calling it "
            "usable."
        )
        yield ""
        yield "| Model | Unit | Accuracy | Quadratic κ | " + " | ".join(
            f"said {grade}" for grade in GRADES
        ) + " |"
        yield "| --- | --- | --- | --- |" + " --- |" * len(GRADES)
        for entry in three:
            level = entry["summary"]["three_class"]
            said = {grade: 0 for grade in GRADES}
            for row in level["confusion"].values():
                for grade, count in row.items():
                    said[grade] += count
            yield (
                f"| {entry['model']} | {entry['unit']} | {_number(level['accuracy'])} | "
                f"{_number(level['kappa_quadratic'])} | "
                + " | ".join(str(said[grade]) for grade in GRADES)
                + " |"
            )
    yield ""
    yield "## 6. What these numbers do not say"
    yield ""
    yield (
        "Every result carries a mark in section 4. `out-of-sample` means the model's page does not "
        "name this dataset among its training data; `unknown` means nobody published what it "
        "trained on, and is never the same statement as `out-of-sample`."
    )
    yield ""
    for model in models:
        yield f"- **{model}** — {_marks(scored, model)}"
    yield ""
    yield "---"
    yield ""
    yield f"**Generated by `python -m benchmarks.quality` on:** {date.today().isoformat()}"


def _first(scored: list[dict[str, object]], model: str = "", unit: str = "") -> dict[str, object]:
    for entry in scored:
        if (not model or entry["model"] == model) and (not unit or entry["unit"] == unit):
            return entry
    raise LookupError(f"nothing scored for {model or unit}")


def _marks(scored: list[dict[str, object]], model: str) -> str:
    marks = sorted({entry["contamination"] for entry in scored if entry["model"] == model})
    return ", ".join(marks)


def _pin(upstream: dict[str, object]) -> str:
    commit = str(upstream.get("commit", ""))
    if commit:
        return f"`{commit[:8]}`"
    return str(upstream.get("version", "—"))


def _number(value: float | None) -> str:
    return "—" if value is None else f"{value:.3f}"
